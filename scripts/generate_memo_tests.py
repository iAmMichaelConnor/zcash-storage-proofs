#!/usr/bin/env python3
"""Generate the ironwood memo known-answer tests in noir/ironwood/src/memo:

- aead_tests.nr: ChaCha20, Poly1305 and ChaCha20-Poly1305 vectors from
  scripts/chacha20poly1305.py (RFC 8439), independent of the Noir implementation;
- native_tests.nr: ephemeral scalars, a memo opening and diversifier hashes from
  the pinned Orchard Rust fixture (fixtures/memo/native-vectors.json);
- digest_tests.nr: independent hashlib digests of the ordered Action ciphertext
  preimages of two complete Actions, exact and in a larger capacity;
- claim_tests.nr: the complete memo claim on the retained case-0 fixture
  (built from native vector 0), whose returned cmx must equal the
  note commitment and the native vector's cmx.

No proof or native build.
"""

import hashlib
import json
from pathlib import Path
import tomllib

from chacha20poly1305 import aead_encrypt, chacha20_block, poly1305
from noir_format import format_file

ROOT = Path(__file__).resolve().parents[1]
MEMO = ROOT / "noir/ironwood/src/memo"
VECTORS = json.loads(
    (ROOT / "fixtures/memo/native-vectors.json").read_text()
)


def arr(x):
    return "[" + ",".join(map(str, x)) + "]"


def fq(x):
    return "Fq::from_limbs(" + arr(x) + ")"


def point(p):
    return "Pallas::from_coordinates(" + fq(p["x"]) + "," + fq(p["y"]) + ",false)"


def note(v):
    n = v["note"]
    return (
        "NoteOpening{receiver:ExpandedReceiver{g_d:"
        + point(n["receiver"]["g_d"])
        + ",pk_d:"
        + point(n["receiver"]["pk_d"])
        + "},value:"
        + n["value"]
        + ",rho:"
        + fq(n["rho"])
        + ",rseed:"
        + arr(n["rseed"])
        + "}"
    )


def h(b, p):
    return list(hashlib.blake2b(bytes(b), digest_size=32, person=p.encode()).digest())


def full(v):
    return v.get(
        "full_action",
        {
            "encrypted_note": v["ciphertext"],
            "value_commitment": [0] * 32,
            "randomized_key": [0] * 32,
            "outgoing_ciphertext": [0] * 80,
        },
    )


def aead_tests():
    lines = [
        "// Public primitive vectors generated by scripts/generate_memo_tests.py.",
        "// Reference: scripts/chacha20poly1305.py (RFC 8439), independent of the Noir implementation.",
    ]
    for name, key, plain in [
        ("zero", bytes(32), bytes(564)),
        ("maximum", bytes([255]) * 32, bytes([255]) * 564),
        ("pattern", bytes(range(32)), bytes(i % 256 for i in range(564))),
    ]:
        cipher = aead_encrypt(key, bytes(12), plain)
        lines.append(
            f"#[test]\nfn aead_{name}() {{ assert(crate::memo::aead::encrypt(std::hint::black_box({arr(key)}),std::hint::black_box({arr(plain)}))=={arr(cipher)}); }}"
        )
        block = chacha20_block(key, 0, bytes(12))
        lines.append(
            f"#[test]\nfn chacha_{name}() {{ assert(crate::memo::aead::block(std::hint::black_box({arr(key)}),0)=={arr(block)}); }}"
        )
    for blocks in [0, 1, 2, 37]:
        key = bytes([255]) * 32
        msg = bytes([255]) * (16 * blocks)
        tag = poly1305(key, msg)
        lines.append(
            f"#[test]\nfn poly1305_maximum_{blocks}() {{ assert(crate::memo::aead::poly1305(std::hint::black_box([[255u8;16];{blocks}]),std::hint::black_box([255u8;32]))=={arr(tag)}); }}"
        )
    return "\n".join(lines) + "\n"


def native_tests():
    lines = [
        "// Generated from the pinned Orchard Rust fixture; public deterministic notes.",
        "use bignum::{BigNum,Pallas_Fq as Fq};",
        "use bigcurve::{BigCurve,Pallas};",
        "use crate::notes::{NoteOpening,ExpandedReceiver,encode_nonidentity};",
    ]
    for i, v in enumerate(VECTORS["vectors"]):
        lines.append(f"fn note_{i}()->NoteOpening {{ {note(v)} }}")
        lines.append(
            f"#[test]\nfn native_esk_{i}() {{ assert(crate::memo::derive_esk(std::hint::black_box(note_{i}())).get_limbs()=={arr(v['esk'])}); }}"
        )
    # One constrained full encryption opening; the compiled full-composition consumer
    # is subsequently executed on cached/zero/maximum vectors and adversarial mutations.
    v = VECTORS["vectors"][0]
    lines.append(
        f"#[test]\nfn native_memo_opening() {{ crate::memo::verify_memo_from_opening(std::hint::black_box(note_0()),{arr(v['raw_receiver'])},{arr(v['ephemeral_key'])},{arr(v['ciphertext'])},{arr(v['memo'])}); }}"
    )
    for i in [0, 1, 15]:
        v = VECTORS["diversifiers"][i]
        lines.append(
            f"#[test]\nfn native_diversifier_{i}() {{ assert(encode_nonidentity(crate::memo::diversifier::diversify_hash(std::hint::black_box({arr(v['input'])})))==encode_nonidentity({point(v['point'])})); }}"
        )
    lines.append(
        f"#[test]\nfn native_empty_diversifier_hash() {{ assert(encode_nonidentity(crate::memo::diversifier::hash_to_curve::<0>([]))==encode_nonidentity({point(VECTORS['empty_hash'])})); }}"
    )
    return "\n".join(lines) + "\n"


def digest_tests():
    vs = VECTORS["vectors"][:2]
    fs = [full(v) for v in vs]
    cs = [
        list(
            sum(int(x) << (120 * i) for i, x in enumerate(v["note"]["rho"])).to_bytes(
                32, "little"
            )
        )
        + v["cmx"]
        + v["ephemeral_key"]
        + v["ciphertext"][:52]
        for v in vs
    ]
    m = h(sum((f["encrypted_note"][52:564] for f in fs), []), "ZTxIdIrnActMH_v6")
    n = h(
        sum(
            (
                f["value_commitment"]
                + f["randomized_key"]
                + f["encrypted_note"][564:]
                + f["outgoing_ciphertext"]
                for f in fs
            ),
            [],
        ),
        "ZTxIdIrnActNH_v6",
    )
    s = (
        "// Generated independent hashlib digest vectors for two complete Actions.\nuse crate::memo::FullActionCiphertext;\nuse crate::transactions::digest::V6Effects;\nfn inputs()->(V6Effects<2>,[FullActionCiphertext;2]){\n let effects=V6Effects{compact_actions:["
        + ",".join(arr(c) for c in cs)
        + "],memos_digest:"
        + arr(m)
        + ",noncompact_digest:"
        + arr(n)
        + ",flags:3,value_balance:[0u8;8],transparent_digest:[0u8;32],sapling_digest:[0u8;32],orchard_digest:[0u8;32],lock_time:0,expiry_height:0};\n let full=["
        + ",".join(
            "FullActionCiphertext{"
            + ",".join(k + ":" + arr(v) for k, v in f.items())
            + "}"
            for f in fs
        )
        + "];\n (effects,full)\n}\n"
    )
    s += """// The same two-Action transaction in a capacity-4 buffer: slots 2 and 3 zero.
fn padded()->(V6Effects<4>,[FullActionCiphertext;4]){
 let (e,f)=inputs();
 let empty=FullActionCiphertext{encrypted_note:[0u8;580],value_commitment:[0u8;32],randomized_key:[0u8;32],outgoing_ciphertext:[0u8;80]};
 let effects=V6Effects{compact_actions:[e.compact_actions[0],e.compact_actions[1],[0u8;148],[0u8;148]],memos_digest:e.memos_digest,noncompact_digest:e.noncompact_digest,flags:e.flags,value_balance:e.value_balance,transparent_digest:e.transparent_digest,sapling_digest:e.sapling_digest,orchard_digest:e.orchard_digest,lock_time:e.lock_time,expiry_height:e.expiry_height};
 (effects,[f[0],f[1],empty,empty])
}
#[test]
fn complete_ordered_digest_preimages(){let (e,f)=std::hint::black_box(inputs());crate::memo::verify_ciphertext_digests(e,2,f);}
#[test(should_fail_with="Memo ciphertext digest mismatch")]
fn reordered_actions_reject_even_when_compact_prefixes_match(){let (mut e,f)=std::hint::black_box(inputs());e.compact_actions=[e.compact_actions[1],e.compact_actions[0]];crate::memo::verify_ciphertext_digests(e,2,[f[1],f[0]]);}
#[test(should_fail_with="Memo ciphertext digest mismatch")]
fn unselected_action_memo_tampering_rejects(){let (e,mut f)=std::hint::black_box(inputs());f[1].encrypted_note[52]=f[1].encrypted_note[52]^1;crate::memo::verify_ciphertext_digests(e,2,f);}
#[test(should_fail_with="Noncompact Action digest mismatch")]
fn unselected_action_tag_tampering_rejects(){let (e,mut f)=std::hint::black_box(inputs());f[1].encrypted_note[564]=f[1].encrypted_note[564]^1;crate::memo::verify_ciphertext_digests(e,2,f);}
#[test]
fn two_actions_verify_in_a_larger_capacity(){let (e,f)=std::hint::black_box(padded());crate::memo::verify_ciphertext_digests(e,2,f);}
#[test(should_fail_with="Nonzero unused Action ciphertext")]
fn truncated_action_count_rejects(){let (e,f)=std::hint::black_box(inputs());crate::memo::verify_ciphertext_digests(e,1,f);}
#[test(should_fail_with="Nonzero unused Action ciphertext")]
fn nonzero_unused_ciphertext_prefix_rejects(){let (e,mut f)=std::hint::black_box(padded());f[2].encrypted_note[0]=1;crate::memo::verify_ciphertext_digests(e,2,f);}
#[test(should_fail_with="Nonzero bounded hash padding")]
fn nonzero_unused_memo_bytes_reject(){let (e,mut f)=std::hint::black_box(padded());f[3].encrypted_note[100]=1;crate::memo::verify_ciphertext_digests(e,2,f);}
#[test(should_fail_with="Action count exceeds capacity")]
fn action_count_above_capacity_rejects(){let (e,f)=std::hint::black_box(inputs());crate::memo::verify_ciphertext_digests(e,3,f);}
"""
    return s


def claim_tests():
    """claim_tests.nr: verify_memo_created_in_block on the retained case-0 fixture
    (built from native vector 0); the returned cmx must equal
    commitment_x(note) and the cmx of native vector 0."""

    def arr(x):
        return "[" + ",".join(str(int(v)) for v in x) + "]"

    def fq(x):
        assert len(x["limbs"]) == 3
        return "Fq::from_limbs(" + arr(x["limbs"]) + ")"

    def point(p):
        return (
            "Pallas::from_coordinates("
            + fq(p["x"])
            + ","
            + fq(p["y"])
            + ","
            + str(p["is_infinity"]).lower()
            + ")"
        )

    def note(n):
        r = n["receiver"]
        return (
            "NoteOpening{receiver:ExpandedReceiver{g_d:"
            + point(r["g_d"])
            + ",pk_d:"
            + point(r["pk_d"])
            + "},value:"
            + str(int(n["value"]))
            + ",rho:"
            + fq(n["rho"])
            + ",rseed:"
            + arr(n["rseed"])
            + "}"
        )

    def effects(e):
        scalars = ("flags", "lock_time", "expiry_height")
        arrays = (
            "memos_digest",
            "noncompact_digest",
            "value_balance",
            "transparent_digest",
            "sapling_digest",
            "orchard_digest",
        )
        assert set(e) == set(scalars) | set(arrays) | {"compact_actions"}
        return (
            "V6Effects{compact_actions:["
            + ",".join(arr(c) for c in e["compact_actions"])
            + "],"
            + ",".join(k + ":" + arr(e[k]) for k in arrays)
            + ","
            + ",".join(k + ":" + str(int(e[k])) for k in scalars)
            + "}"
        )

    def inclusion(w):
        assert len(w["siblings"]) == 32
        return (
            "Inclusion{effects:"
            + effects(w["effects"])
            + ",header:"
            + arr(w["header"])
            + ",siblings:["
            + ",".join(arr(s) for s in w["siblings"])
            + "],"
            + ",".join(
                k + ":" + str(int(w[k]))
                for k in ("action_index", "tx_index", "tx_count")
            )
            # The fixture transaction is exact: its Action count is the buffer size.
            + ",action_count:"
            + str(len(w["effects"]["compact_actions"]))
            + "}"
        )

    def full(f):
        keys = (
            "encrypted_note",
            "value_commitment",
            "randomized_key",
            "outgoing_ciphertext",
        )
        assert set(f) == set(keys)
        return (
            "FullActionCiphertext{" + ",".join(k + ":" + arr(f[k]) for k in keys) + "}"
        )

    d = tomllib.loads(
        (ROOT / "fixtures/memo/case-0.toml").read_text()
    )
    assert len(d["full"]) == 1 and len(d["witness"]["effects"]["compact_actions"]) == 1
    vector = VECTORS["vectors"][0]
    # case-0 is built from vector 0 (scripts/prepare_memo_fixtures.py).
    assert [str(x) for x in vector["note"]["rho"]] == d["note"]["rho"]["limbs"]
    assert list(vector["note"]["rseed"]) == d["note"]["rseed"]
    s = (
        "// Generated by scripts/generate_memo_tests.py from fixtures/memo/case-0.toml\n"
        "// and native vector 0, then `nargo fmt`.\n"
        "// Execution only.\n"
        "use crate::memo::FullActionCiphertext;\n"
        "use bigcurve::{BigCurve, Pallas};\n"
        "use bignum::{BigNum, Pallas_Fq as Fq};\n"
        "use crate::notes::{ExpandedReceiver, NoteOpening};\n"
        "use crate::transactions::digest::V6Effects;\n"
        "use crate::transactions::effects::Inclusion;\n"
        "fn case_0()->(NoteOpening,[u8;43],[u8;512],Inclusion<1,32>,[FullActionCiphertext;1],[u8;32]){("
        + note(d["note"])
        + ","
        + arr(d["raw_receiver"])
        + ","
        + arr(d["memo"])
        + ","
        + inclusion(d["witness"])
        + ",["
        + full(d["full"][0])
        + "],"
        + arr(d["accepted_header_hash"])
        + ")}\n"
        "// cmx of native vector 0, from the pinned Orchard Rust fixture.\n"
        "global NATIVE_CMX_0: [u8; 32] = " + arr(vector["cmx"]) + ";\n"
        "#[test]\n"
        "fn claim_returns_note_commitment_as_cmx(){\n"
        "let (note,raw_receiver,memo,witness,full,header_hash)=std::hint::black_box(case_0());\n"
        "let (_txid,cmx)=crate::memo::verify_memo_created_in_block(note,raw_receiver,memo,witness,full,header_hash);\n"
        "// Recomputed from the opening with the function the claim uses internally;\n"
        "// not read from the Action bytes. NATIVE_CMX_0 is the independent value.\n"
        "let expected=crate::notes::commitment_x(note).to_le_bytes();\n"
        'assert(cmx==expected,"Returned cmx is not the note commitment");\n'
        'assert(cmx==NATIVE_CMX_0,"Returned cmx is not the native vector cmx");\n'
        "}\n"
        "// The same one-Action transaction in a capacity-2 buffer: the unused\n"
        "// Action slot and ciphertext entry are zero, and the claim is unchanged.\n"
        "#[test]\n"
        "fn claim_verifies_in_a_larger_action_capacity(){\n"
        "let (note,raw_receiver,memo,w,full,header_hash)=std::hint::black_box(case_0());\n"
        "let (txid,cmx)=crate::memo::verify_memo_created_in_block(note,raw_receiver,memo,w,full,header_hash);\n"
        "let e=w.effects;\n"
        "let effects=V6Effects{compact_actions:[e.compact_actions[0],[0u8;148]],memos_digest:e.memos_digest,noncompact_digest:e.noncompact_digest,flags:e.flags,value_balance:e.value_balance,transparent_digest:e.transparent_digest,sapling_digest:e.sapling_digest,orchard_digest:e.orchard_digest,lock_time:e.lock_time,expiry_height:e.expiry_height};\n"
        "let wide=Inclusion::<2,32>{effects,header:w.header,siblings:w.siblings,action_index:0,tx_index:w.tx_index,tx_count:w.tx_count,action_count:1};\n"
        "let empty=FullActionCiphertext{encrypted_note:[0u8;580],value_commitment:[0u8;32],randomized_key:[0u8;32],outgoing_ciphertext:[0u8;80]};\n"
        "let (txid2,cmx2)=crate::memo::verify_memo_created_in_block(note,raw_receiver,memo,wide,[full[0],empty],header_hash);\n"
        'assert((txid2==txid)&(cmx2==cmx),"Capacity changed the claim");\n'
        "}\n"
    )
    return s


if __name__ == "__main__":
    for name, text in [
        ("aead_tests.nr", aead_tests()),
        ("native_tests.nr", native_tests()),
        ("digest_tests.nr", digest_tests()),
        ("claim_tests.nr", claim_tests()),
    ]:
        (MEMO / name).write_text(text)
        format_file(MEMO / name)
        print(f"wrote {(MEMO / name).relative_to(ROOT)}")
