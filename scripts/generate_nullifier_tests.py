#!/usr/bin/env python3
"""Generate the nullifier and membership tests of ironwood_slow_tests from
fixtures/ironwood_notes/nullifier-reference.json.

The expected cmx, nf and root come from the pinned native Orchard reference
(regenerated by scripts/generate_native_fixtures.py). The tests check that derive_owned and
derive_member bind ownership or membership and the nullifier to ONE opening, and
that verify_contents_membership / verify_owned_membership accept the native path.
The `*_with_witness_inputs` tests pass vector 0 through std::hint::black_box, so
the constrained relation runs on witness values instead of being folded at
compile time. Execution only; no proof.
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REF = (
    ROOT
    / "fixtures/ironwood_notes/nullifier-reference.json"
)
OUT = ROOT / "noir/ironwood_slow_tests/src/nullifier_tests.nr"


def limbs(x):
    return "[" + ", ".join(str(int(v)) for v in x) + "]"


def fq(x):
    return f"Fq::from_limbs({limbs(x)})"


def fr(x):
    return f"Fr::from_limbs({limbs(x)})"


def point(p):
    return f"Pallas::from_coordinates({fq(p['x'])}, {fq(p['y'])}, false)"


def vector(i, v):
    n, o = v["note"], v["ownership"]
    r = n["receiver"]
    sib = ", ".join(fq(s) for s in v["siblings"])
    return f"""fn note_{i}() -> NoteOpening {{
    NoteOpening {{
        receiver: ExpandedReceiver {{ g_d: {point(r["g_d"])}, pk_d: {point(r["pk_d"])} }},
        value: {int(n["value"])},
        rho: {fq(n["rho"])},
        rseed: [{", ".join(str(int(b)) for b in n["rseed"])}],
    }}
}}
fn spend_{i}() -> SpendAuthority {{
    SpendAuthority {{ ask: {fr(o["ask"])}, nk: {fq(o["nk"])}, rivk: {fr(o["rivk"])} }}
}}
fn view_{i}() -> ViewingAuthority {{
    ViewingAuthority {{ ak: {point(v["ak"])}, nk: {fq(o["nk"])}, rivk: {fr(o["rivk"])} }}
}}
fn siblings_{i}() -> [Fq; 32] {{
    [{sib}]
}}
global POSITION_{i}: u32 = {int(v["position"])};
fn root_{i}() -> Fq {{
    {fq(v["expected_root"])}
}}
fn cmx_{i}() -> Fq {{
    {fq(v["expected_cmx"])}
}}
fn nf_{i}() -> Fq {{
    {fq(v["expected_nf"])}
}}
"""


def main():
    vs = json.loads(REF.read_text())["vectors"]
    assert len(vs) >= 2
    body = "".join(vector(i, v) for i, v in enumerate(vs[:2]))
    OUT.write_text(f"""// Generated by scripts/generate_nullifier_tests.py from
// fixtures/ironwood_notes/nullifier-reference.json. Do not edit. Execution only.
use bigcurve::{{BigCurve, Pallas}};
use bignum::{{BigNum, Pallas_Fq as Fq, Pallas_Fr as Fr}};
use ironwood::notes::{{
    ExpandedReceiver, NoteOpening,
    nullifier::{{derive_member, derive_owned, derive_with_commitment}},
    ownership::{{SpendAuthority, verify, ViewingAuthority}},
    verify_contents_membership, verify_owned_membership,
}};
use std::hint::black_box;
{body}
#[test]
fn owned_and_linked_nullifier_of_one_opening_match_the_native_reference() {{
    let (cmx, nf) = derive_owned(note_0(), spend_0());
    assert(cmx.get_limbs() == cmx_0().get_limbs());
    assert(nf.get_limbs() == nf_0().get_limbs());
    let (cmx_v, nf_v) = derive_with_commitment(note_0(), view_0());
    assert((cmx_v.get_limbs() == cmx.get_limbs()) & (nf_v.get_limbs() == nf.get_limbs()));
}}
#[test]
fn member_nullifier_matches_the_native_reference() {{
    let (cmx, nf) = derive_member(note_0(), view_0(), POSITION_0, siblings_0(), root_0());
    assert(cmx.get_limbs() == cmx_0().get_limbs());
    assert(nf.get_limbs() == nf_0().get_limbs());
}}
#[test(should_fail_with = "Note receiver does not match viewing authority")]
fn owned_rejects_a_spending_authority_for_another_receiver() {{
    let mut authority = spend_0();
    authority.rivk = Fr::from_limbs([1, 0, 0]);
    let _ = derive_owned(note_0(), authority);
}}
#[test(should_fail_with = "Ironwood note membership failed")]
fn member_rejects_an_opening_outside_the_root() {{
    let _ = derive_member(note_1(), view_1(), POSITION_0, siblings_0(), root_0());
}}
// verify_owned_membership runs verify_contents_membership and then the
// spending-authority relation, so one call covers both positives.
#[test]
fn owned_membership_accepts_the_native_path() {{
    verify_owned_membership(note_0(), spend_0(), POSITION_0, siblings_0(), root_0());
}}
#[test]
fn contents_membership_with_witness_inputs() {{
    verify_contents_membership(
        black_box(note_0()),
        black_box(POSITION_0),
        black_box(siblings_0()),
        black_box(root_0()),
    );
}}
#[test]
fn linked_nullifier_with_witness_inputs() {{
    let (cmx, nf) = derive_with_commitment(black_box(note_0()), black_box(view_0()));
    assert(cmx.get_limbs() == cmx_0().get_limbs());
    assert(nf.get_limbs() == nf_0().get_limbs());
}}
#[test]
fn spending_authority_with_witness_inputs() {{
    verify(black_box(note_0().receiver), black_box(spend_0()));
}}
// Position 1 swaps the leaf and its sibling at level 0, so the root differs.
#[test(should_fail_with = "Ironwood note membership failed")]
fn contents_membership_rejects_another_position() {{
    verify_contents_membership(note_0(), POSITION_0 + 1, siblings_0(), root_0());
}}
""")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
