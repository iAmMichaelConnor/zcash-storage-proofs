def merkle_path(count, index, depth=3):
    level, pos, path = LEAVES[:count], index, []
    while len(level) > 1:
        path.append(level[pos ^ 1] if pos ^ 1 < len(level) else level[pos])
        if len(level) % 2:
            level = level + [level[-1]]
        level = [sha256d(level[i] + level[i + 1]) for i in range(0, len(level), 2)]
        pos //= 2
    assert len(path) <= depth
    return path + [bytes(32)] * (depth - len(path)), level[0]


