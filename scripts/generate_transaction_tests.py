W_MEMOS, W_NC, W_FLAGS, W_VB = b"\x44" * 32, b"\x55" * 32, 3, bytes(8)


def scan_action(i):
    a = bytearray((hashlib.sha256(b"scan action %d" % i).digest() * 5)[:148])
    a[31] &= 0x3F  # a canonical nullifier (below p), so it can be queried
    return bytes(a)


ACTS = [scan_action(i) for i in range(3)]


def wide_txid(version, lock, actions):
    base = header_digest(version, lock) + W_T + W_S + W_O
    if version == 5:
        return b2(base, b"ZcashTxHash_" + le(BRANCH))
    iw = b2(b"", b"ZTxIdIronwd_H_v6")
    if actions:
        compact = b2(b"".join(actions), b"ZTxIdIrnActCH_v6")
        iw = b2(compact + W_MEMOS + W_NC + bytes([W_FLAGS]) + W_VB, b"ZTxIdIronwd_H_v6")
    return b2(base + iw, b"ZcashTxHash_" + le(BRANCH))


def wide_row(version, lock, actions):
    slots = b"".join(actions) + bytes(148 * (W_A - len(actions)))
    if version == 5:  # a V5 row carries no Ironwood fields
        fields = bytes(32 + 32 + 1 + 8)
    else:
        fields = W_MEMOS + W_NC + bytes([W_FLAGS]) + W_VB
    row = (
        slots
        + fields
        + W_T
        + W_S
        + W_O
        + le(lock)
        + le(0)
        + le(version)
        + le(len(actions))
    )
    assert len(row) == 185 + 148 * W_A
    return row


def v4_body(length=80):
    """A one-input, one-output transparent V4 transaction (old harness body)."""
    script = bytes([81]) * (length - 80)
    result = (
        bytes.fromhex("0400008085202f89")
        + b"\x01"
        + bytes([33]) * 32
        + bytes(4)
        + bytes([len(script)])
        + script
        + bytes([255]) * 4
        + b"\x01"
        + (1).to_bytes(8, "little")
        + b"\x01\x51"
        + bytes(4)  # lock_time
        + bytes(4)  # expiry_height
        + bytes(8)  # valueBalance
        + bytes(3)  # no spends, outputs or JoinSplits
    )
    assert len(result) == length
    return result


def merkle_root(leaves):
    while len(leaves) > 1:
        if len(leaves) % 2:
            leaves = leaves + [leaves[-1]]
        leaves = [sd(leaves[i] + leaves[i + 1]) for i in range(0, len(leaves), 2)]
    return leaves[0]


def wide_chain(prev, mixed, tag):
    """Block 0: [V5 or V4, V6 one Action]; block 1: [V5, V6 two Actions, V6 none]."""
    plan = [[(5, 1, []), (6, 2, ACTS[:1])], [(5, 3, []), (6, 4, ACTS[1:3]), (6, 5, [])]]
    out = b""
    for b, txs in enumerate(plan):
        leaves, rows = [], []
        for i, (version, lock, actions) in enumerate(txs):
            if mixed and b == 0 and i == 0:
                body = v4_body()
                leaves.append(sd(body))
                rows.append(
                    bytes(185 + 148 * W_A - 8)
                    + le(4)
                    + le(0)
                    + le(len(body))
                    + body
                    + bytes(W_RAW - len(body))
                )
                continue
            leaves.append(wide_txid(version, lock, actions))
            row = wide_row(version, lock, actions)
            rows.append(row + le(0) + bytes(W_RAW) if mixed else row)
        blank = bytes(len(rows[0]))
        h = header(prev, merkle_root(leaves), tag + b)
        out += h + le(len(txs)) + b"".join(rows) + blank * (W_TX - len(txs))
        prev = sd(h)
    return out, prev


