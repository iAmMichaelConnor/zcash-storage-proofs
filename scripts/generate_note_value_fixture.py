#!/usr/bin/env python3
"""Write examples/note_value/tests/src/fixture.nr: the capsules of the note_value TXE tests,
which the aztec_contents and aztec_contents_capsules tests also use.

The capsules carry the first native reference note (fixtures/ironwood_notes/reference.json)
under the synthetic header of fixtures/ironwood_headers/header-mainnet.json, whose
history node commits to the note's synthetic tree root (scripts/synthetic_fixtures.py).
CMX is the reference note's extracted commitment, as the adapter returns it.
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
from noir_format import format_file  # noqa: E402
from synthetic_fixtures import contents_manifest  # noqa: E402

OUT = ROOT / "examples/note_value/tests/src/fixture.nr"


def read(path):
    return json.loads((ROOT / path).read_text())


def capsule_bytes(oracle):
    return [int.from_bytes(bytes(v), "big") for v in oracle["result"]["values"][1]]


reference = read("fixtures/ironwood_notes/reference.json")["vectors"][0]
manifest = contents_manifest(
    reference, read("fixtures/ironwood_headers/header-mainnet.json")
)
inputs = manifest["parent_inputs"]
oracles = manifest["parent_prefix_oracles"]
text = "// Generated by scripts/generate_note_value_fixture.py; do not edit.\n"
for name, kind, values in [
    ("HASH", "u8", inputs["expected_hash"]),
    ("HEADER", "Field", capsule_bytes(oracles[0])),
    ("NOTE", "Field", capsule_bytes(oracles[1])),
]:
    text += f"pub global {name}: [{kind}; {len(values)}] = [{','.join(map(str, values))}];\n"
text += f"pub global HEIGHT: u32 = {inputs['header_height']};\n"
text += f"pub global VALUE: u64 = {reference['note']['value']};\n"
cmx = list(bytes.fromhex(reference["cmx_hex"]))
limbs = reference["expected_cmx"]
assert int.from_bytes(bytes(cmx), "little") == sum(int(v) << (120 * i) for i, v in enumerate(limbs))
text += f"pub global CMX: [u8; 32] = [{','.join(map(str, cmx))}];\n"
OUT.write_text(text)
format_file(OUT)
