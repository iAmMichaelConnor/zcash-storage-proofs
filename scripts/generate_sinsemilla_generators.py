#!/usr/bin/env python3
"""Write noir/ironwood/src/sinsemilla/generators.nr from the Rust reference's Sinsemilla constants.

Usage: generate_sinsemilla_generators.py SINSEMILLA_BINARY

The binary is the `sinsemilla` bin of reference/notes (the sinsemilla 0.2.0 crate);
scripts/generate_native_fixtures.py builds it and runs this script. Every point is
checked to be a canonical affine point of Pallas (y^2 = x^3 + 5) before it is written.
"""

import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
from noir_format import format_file  # noqa: E402

P = 0x40000000000000000000000000000000224698FC094CF91B992D30ED00000001
OUT = ROOT / "noir/ironwood/src/sinsemilla/generators.nr"


def coordinates(point):
    x, y = (int.from_bytes(bytes.fromhex(c), "little") for c in point)
    assert x < P and y < P and (y * y - x**3 - 5) % P == 0, "not a Pallas point"
    return x, y


def limbs(v):
    return [v % 2**120, (v >> 120) % 2**120, v >> 240]


def constant(point):
    x, y = coordinates(point)
    return f"comptime {{ Pallas::from_coordinates(Fq::from_limbs({limbs(x)}), Fq::from_limbs({limbs(y)}), false) }}"


def select(names):
    *first, last = names
    text = "".join(f"if domain == {i} {{ {n} }} else " for i, n in enumerate(first))
    return text + f"{{ {last} }}"


data = json.loads(subprocess.check_output([sys.argv[1]], text=True))
assert len(data["q"]) == 3 and len(data["r"]) == 2 and len(data["s"]) == 1024
text = "// Generated by scripts/generate_sinsemilla_generators.py from the sinsemilla 0.2.0 crate\n"
text += "// (reference/notes/src/bin/sinsemilla.rs). Do not edit.\n"
text += "use bignum::{BigNum, Pallas_Fq as Fq};\nuse bigcurve::{BigCurve, Pallas};\n"
for name, letter, points in [("domain_q", "q", data["q"]), ("domain_r", "r", data["r"])]:
    names = [f"{letter}{i}" for i in range(len(points))]
    text += f"pub fn {name}(domain: u8) -> Pallas {{\n    assert(domain < {len(points)});\n"
    text += "".join(f"    let {n} = {constant(p)};\n" for n, p in zip(names, points))
    text += f"    {select(names)}\n}}\n"
# The S table is six globals (one per coordinate limb) that `s` indexes. Declared as
# local arrays of `s`, which the hash calls once per chunk, they make Brillig
# compilation fail with "Stack frame too deep" (noir-lang/noir#14162).
s = [coordinates(p) for p in data["s"]]
for c, axis in enumerate("XY"):
    for limb in range(3):
        values = ", ".join(str(limbs(point[c])[limb]) for point in s)
        text += f"global S_{axis}{limb}: [u128; 1024] = [{values}];\n"
text += (
    "#[no_predicates]\npub fn s(index: u16) -> Pallas {\n    assert(index < 1024);\n"
    "    let i = index as u32;\n"
    "    Pallas::from_coordinates_unsafe(\n"
    "        Fq::from_limbs([S_X0[i], S_X1[i], S_X2[i]]),\n"
    "        Fq::from_limbs([S_Y0[i], S_Y1[i], S_Y2[i]]),\n"
    "        false,\n    )\n}\n"
)
OUT.write_text(text)
format_file(OUT)
