#!/usr/bin/env python3
"""Generate ironwood_nullifier_absence_state NullifierAbsenceNote tests.

The packed fields are computed here in Python; the note hashes come from the Aztec 6.0.0
SDK (@aztec-labs/foundation poseidon2HashWithSeparator with the @aztec-labs/constants
NOTE_HASH separator), over the preimage [storage_slot, packed note, owner, randomness]
that the aztec-nr #[note] macro hashes. No value comes from Noir.

The SDK packages are read from $AZTEC_NODE_MODULES (default
~/.aztec/current/node_modules, where the Aztec installer puts them), or install them
with `npm install @aztec-labs/foundation@6.0.0 @aztec-labs/constants@6.0.0`.
Plain `nargo test`; no TXE oracle, no proof.
"""

import copy
import json
import os
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "examples/nullifier_absence_state/contract/src/nullifier_absence_note_tests.nr"
SDK = (
    Path(
        os.environ.get(
            "AZTEC_NODE_MODULES", Path.home() / ".aztec/current/node_modules"
        )
    )
    / "@aztec-labs"
)

BASE = dict(
    queried_nf=[255] * 32,
    tip_hash=list(range(32)),
    height=3428144,
    is_testnet=False,
    activation_height=3428143,
    owner=4660,
    storage_slot=123,
    randomness=987654321,
)


def cases():
    yield "baseline", BASE
    for field in ["queried_nf", "tip_hash"]:
        for offset in [0, 16]:
            v = copy.deepcopy(BASE)
            v[field][offset] ^= 1
            yield f"{field}_{'lo' if offset == 0 else 'hi'}", v
    for field in ["height", "activation_height", "owner", "storage_slot", "randomness"]:
        v = copy.deepcopy(BASE)
        v[field] += 1
        yield field, v
    v = copy.deepcopy(BASE)
    v["is_testnet"] = True
    yield "is_testnet", v


def packed(v):
    words = [
        int.from_bytes(bytes(v[f][o : o + 16]), "little")
        for f in ["queried_nf", "tip_hash"]
        for o in [0, 16]
    ]
    return words + [v["height"], int(v["is_testnet"]), v["activation_height"]]


def preimage(v):
    return [v["storage_slot"]] + packed(v) + [v["owner"], v["randomness"]]


NODE = """
const [root, input] = process.argv.slice(1);
const { poseidon2HashWithSeparator } = await import(root + "/foundation/dest/crypto/poseidon/index.js");
const { DomainSeparator } = await import(root + "/constants/dest/constants.gen.js");
const out = [];
for (const p of JSON.parse(input)) {
  out.push((await poseidon2HashWithSeparator(p.map(BigInt), DomainSeparator.NOTE_HASH)).toString());
}
console.log(JSON.stringify(out));
"""


def sdk_hashes(preimages):
    r = subprocess.run(
        [
            "node",
            "--input-type=module",
            "-e",
            NODE,
            str(SDK),
            json.dumps([[str(x) for x in p] for p in preimages]),
        ],
        capture_output=True,
        text=True,
        check=True,
    )
    return json.loads(r.stdout)


def arr(x):
    return "[" + ", ".join(str(int(v)) for v in x) + "]"


def check(name, v, h, indent):
    p = " " * indent
    return f"""{p}#[test]
{p}fn {name}_note_hash_matches_sdk() {{
{p}    check(
{p}        {arr(v["queried_nf"])},
{p}        {arr(v["tip_hash"])},
{p}        {v["height"]},
{p}        {str(v["is_testnet"]).lower()},
{p}        {v["activation_height"]},
{p}        {arr(packed(v))},
{p}        {v["owner"]},
{p}        {v["storage_slot"]},
{p}        {v["randomness"]},
{p}        {h},
{p}    );
{p}}}
"""


def render():
    named = list(cases())
    hashes = sdk_hashes([preimage(v) for _, v in named])
    assert len(set(hashes)) == len(hashes), "a field does not change the SDK note hash"
    release = "".join(check(n, v, h, 4) for (n, v), h in zip(named[1:], hashes[1:]))
    return f"""// Generated by scripts/generate_nullifier_absence_note_tests.py. Do not edit.
// Packed fields from a Python model; note hashes from the Aztec 6.0.0 SDK
// Poseidon2 (@aztec-labs/foundation) over [storage_slot, packed note, owner,
// randomness] with the NOTE_HASH separator. Execution only.
use crate::nullifier_absence_note::NullifierAbsenceNote;
use aztec::note::note_interface::NoteHash;
use aztec::protocol::{{address::AztecAddress, traits::{{FromField, Packable}}}};
use ironwood::transactions::nullifier_absence_state::State;
// Packs the state's note, unpacks it, recovers the state, and hashes the note.
fn check(
    queried_nf: [u8; 32],
    tip_hash: [u8; 32],
    height: u32,
    is_testnet: bool,
    activation_height: u32,
    expected_packed: [Field; 7],
    owner: Field,
    storage_slot: Field,
    randomness: Field,
    expected_hash: Field,
) {{
    let note = NullifierAbsenceNote::from_state(State {{ queried_nf, tip_hash, height, is_testnet, activation_height }});
    let packed = note.pack();
    assert(packed == expected_packed);
    let unpacked = NullifierAbsenceNote::unpack(packed);
    assert(unpacked == note);
    let state = unpacked.state();
    assert(state.queried_nf == queried_nf);
    assert(state.tip_hash == tip_hash);
    assert(state.height == height);
    assert(state.is_testnet == is_testnet);
    assert(state.activation_height == activation_height);
    let hash = note.compute_note_hash(AztecAddress::from_field(owner), storage_slot, randomness);
    assert(hash == expected_hash);
}}
{check(*named[0], hashes[0], 0)}// Field binding: each case changes one field of the baseline; the SDK hashes
// of all cases are distinct (checked by the generator).
mod extended {{
    use super::check;
{release}}}
"""


def main():
    OUT.write_text(render())
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
